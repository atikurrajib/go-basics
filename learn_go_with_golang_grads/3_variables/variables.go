package main

import (
	"fmt"
)

func main() {

	var name = "golang"
	// var name string = "golang" 
	fmt.Println(name)

	var isAdult bool = true
	fmt.Println(isAdult)

	var age int = 30
	fmt.Println(age)

	// shorthand syntax
	name2 := "golang"
	fmt.Println(name2)

	var price = 50.5 
	// var price float = 50.5
	// price := 50.5
	fmt.Println(price)
}
